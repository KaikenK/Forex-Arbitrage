"""
Write a SCRIPTED demo session that the Replay button plays through the real
pipeline (aligner -> ArbitrageEngine -> ranker -> /live, dashboard).

Why: NSE vs BSE USD/INR books are rarely crossed, and BSE often has no orders
at all, so a short live demo may show no arbitrage. This session shows what
detection looks like when a cross does happen. It is NOT market data:

  * the provider is "demo", so legs are named replay_demo_nse_usdinr /
    replay_demo_bse_usdinr and show as "Demo" everywhere;
  * the folder is research/recordings/DEMO-scripted-crossings and contains a
    README saying it is scripted.

The NSE leg is anchored on your last real recorded NSE mid when one exists, so
prices look realistic; BSE is generated around it with a wider spread, a few
one-sided periods, and crossed books of 0.25-1.0 paise every 10-20 s, lasting 1-3 s.

    python research/make_demo_session.py               # 10 minutes, a cross every 10-20 s
    python research/make_demo_session.py --minutes 5 --seed 7
"""

from __future__ import annotations

import argparse
import json
import random
from datetime import date, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "research" / "recordings"
NAME = "DEMO-scripted-crossings"
TICK = 0.0025


def _last_real_nse(root: Path):
    """(mid, expiry) of the newest real two-sided NSE quote recorded, else None."""
    for day in sorted((d for d in root.iterdir() if d.is_dir() and not d.name.startswith("DEMO")), reverse=True):
        for f in sorted(day.glob("*.jsonl")):
            if f.name == "opportunities.jsonl":
                continue
            best = None
            for line in f.read_text(encoding="utf-8").splitlines():
                try:
                    r = json.loads(line)
                except ValueError:
                    continue
                if r.get("exchange") == "NSE" and r.get("bid") and r.get("ask") and r["bid"] < r["ask"]:
                    best = ((r["bid"] + r["ask"]) / 2, r.get("expiry"))
            if best:
                return best
    return None


def _snap(x: float) -> float:
    return round(round(x / TICK) * TICK, 4)


def _default_expiry() -> str:
    d = date.today().replace(day=28)
    if d <= date.today() + timedelta(days=2):
        d = (d + timedelta(days=35)).replace(day=28)
    return d.isoformat()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--minutes", type=float, default=10.0)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--root", default=str(ROOT))
    args = ap.parse_args()

    root = Path(args.root)
    root.mkdir(parents=True, exist_ok=True)
    anchor = _last_real_nse(root)
    mid, expiry = (anchor if anchor else (88.70, None))
    expiry = expiry or _default_expiry()
    rng = random.Random(args.seed)

    out = root / NAME
    out.mkdir(exist_ok=True)
    for f in out.glob("*.jsonl"):
        f.unlink()
    (out / "README.txt").write_text(
        "SCRIPTED DEMO SESSION - not market data.\n"
        f"Generated by research/make_demo_session.py (seed {args.seed}).\n"
        f"NSE anchored at {mid:.4f} ({'last real recorded NSE mid' if anchor else 'default level'}); "
        "BSE and the crossings are simulated to show what detection looks like.\n", encoding="utf-8")

    contract = {"NSE": ("DEMO_NSE|1", "USDINR FUT (DEMO, scripted)"),
                "BSE": ("DEMO_BSE|1", "USDINR FUT (DEMO, scripted)")}
    t0 = 1_800_000_000_000
    n = int(args.minutes * 60)
    # cross windows: every 10-20 s, lasting 1-3 polls (frequent enough for a live demo)
    crosses, t = {}, 5
    while t < n:
        size = rng.choice([1, 1, 2, 2, 3, 4])            # ticks: 0.25 .. 1.0 paise
        for k in range(rng.randint(1, 3)):
            crosses[t + k] = (size, rng.choice([1, -1]))
        t += rng.randint(10, 20)
    one_sided = {s for s in range(n) if (s // 20) % 9 == 4}   # BSE drops its asks now and then

    rows, n_cross = [], 0
    for s in range(n):
        mid += rng.gauss(0, 0.0008)
        nse_bid = _snap(mid - TICK / 2 - (TICK if rng.random() < 0.3 else 0))
        nse_ask = _snap(nse_bid + TICK * rng.choice([1, 1, 2]))
        if s in crosses:
            size, side = crosses[s]
            n_cross += 1
            if side > 0:    # BSE bid above NSE ask: buy NSE, sell BSE
                bse_bid = _snap(nse_ask + size * TICK)
                bse_ask = _snap(bse_bid + 2 * TICK)
            else:           # BSE ask below NSE bid: buy BSE, sell NSE
                bse_ask = _snap(nse_bid - size * TICK)
                bse_bid = _snap(bse_ask - 2 * TICK)
        else:
            bse_bid = _snap(nse_bid - TICK * rng.choice([1, 2, 3]))
            bse_ask = _snap(nse_ask + TICK * rng.choice([1, 2, 3]))
        books = {"NSE": (nse_bid, nse_ask), "BSE": (bse_bid, None if (s in one_sided and s not in crosses) else bse_ask)}
        ts = t0 + s * 1000
        for ex, (bid, ask) in books.items():
            bq, aq = rng.randint(20, 600), rng.randint(20, 600)
            key, tsym = contract[ex]
            rows.append(json.dumps({
                "symbol": "USDINR", "instrument_key": key, "provider": "demo", "exchange": ex,
                "trading_symbol": tsym, "expiry": expiry, "bid": bid, "ask": ask,
                "bid_qty": bq, "ask_qty": aq if ask else 0, "last": round((bid + (ask or bid)) / 2, 4),
                "exchange_ts_ms": ts - 300, "recv_ts_ms": ts,
                "depth": {"bids": [{"price": bid, "qty": bq}],
                          "asks": [{"price": ask, "qty": aq}] if ask else []},
            }))
    (out / "demo.jsonl").write_text("\n".join(rows) + "\n", encoding="utf-8")
    print(f"Wrote {out} ({n} s, {n_cross} crossed polls, NSE anchor {mid:.4f}, expiry {expiry}).")
    print("Start the server, open the dashboard or /live, choose Replay and pick "
          f"'{NAME}' from the session list.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
